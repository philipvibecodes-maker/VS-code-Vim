/**
 * The set of VSCodeVim-bound keys which conflict with VS Code's own default
 * keybindings on the given platform (defaults to the current platform).
 */
export function vscodeConflictingKeys(platform: string = process.platform): Set<string> {
  return VSCODE_CONFLICTING_KEYS[platform] ?? VSCODE_CONFLICTING_KEYS.win32;
}
